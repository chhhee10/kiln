//! Loop feedback and generated worker memory files.

use crate::render::{one_line, or_none};
use kiln_types::qa::{Decision, PassFail, QaReport, ReviewVerdict, Severity};
use kiln_types::{PRODUCT_NAME, Task, WorkerRole};
use std::fmt::Write as _;

/// Format the feedback that sends a task back to the Builder.
///
/// Includes QA's failing criteria (with notes and evidence) and test
/// failures, the Reviewer's findings when changes were requested (or any
/// major/critical finding on an approval), and the human note. Returns an
/// empty string when there is nothing to act on.
pub fn feedback_from(
    qa: Option<&QaReport>,
    verdict: Option<&ReviewVerdict>,
    human: Option<&str>,
) -> String {
    let mut s = String::new();

    if let Some(r) = qa {
        let failures: Vec<_> = r
            .criteria
            .iter()
            .filter(|c| c.status == PassFail::Fail)
            .collect();
        if !failures.is_empty() || r.tests.failed > 0 || (r.criteria.is_empty() && !r.passed()) {
            s.push_str("## QA failed\n\n");
            if !r.summary.trim().is_empty() {
                let _ = writeln!(s, "{}\n", r.summary.trim());
            }
            if r.criteria.is_empty() {
                s.push_str("QA reported no per-criterion results.\n");
            }
            for c in failures {
                let _ = writeln!(s, "- ✕ **{}**", one_line(&c.criterion));
                if !c.notes.trim().is_empty() {
                    let _ = writeln!(s, "  {}", c.notes.trim().replace('\n', "\n  "));
                }
                if !c.evidence.is_empty() {
                    let _ = writeln!(
                        s,
                        "  Evidence: {}",
                        c.evidence
                            .iter()
                            .map(|e| format!("`{e}`"))
                            .collect::<Vec<_>>()
                            .join(", ")
                    );
                }
            }
            if r.tests.failed > 0 {
                let _ = writeln!(
                    s,
                    "- Tests: {} failed, {} passed.",
                    r.tests.failed, r.tests.passed
                );
                if let Some(a) = r
                    .tests
                    .failing_assertion
                    .as_deref()
                    .filter(|a| !a.trim().is_empty())
                {
                    let _ = writeln!(
                        s,
                        "  First failing assertion: `{}`",
                        one_line(a).replace('`', "'")
                    );
                }
            }
            s.push('\n');
        }
    }

    if let Some(v) = verdict {
        let mut findings: Vec<_> = v
            .findings
            .iter()
            .filter(|f| v.decision == Decision::ChangesRequested || f.severity >= Severity::Major)
            .collect();
        if v.decision == Decision::ChangesRequested || !findings.is_empty() {
            findings.sort_by_key(|f| std::cmp::Reverse(f.severity));
            let title = if v.decision == Decision::ChangesRequested {
                "Reviewer requested changes"
            } else {
                "Reviewer findings"
            };
            let _ = writeln!(s, "## {title}\n");
            if !v.summary.trim().is_empty() {
                let _ = writeln!(s, "{}\n", v.summary.trim());
            }
            for f in findings {
                let loc = match (&f.file, f.line) {
                    (Some(file), Some(line)) => format!(" `{file}:{line}`"),
                    (Some(file), None) => format!(" `{file}`"),
                    _ => String::new(),
                };
                let sev = format!("{:?}", f.severity).to_lowercase();
                let _ = writeln!(s, "- [{sev}]{loc} — {}", one_line(&f.message));
            }
            s.push('\n');
        }
    }

    if let Some(h) = human.map(str::trim).filter(|h| !h.is_empty()) {
        s.push_str("## Note from a human\n\n");
        let _ = writeln!(s, "{h}\n");
    }

    s.trim_end().to_string()
}

/// Content for the `AGENTS.md` / `CLAUDE.md` file Kiln writes into a
/// worker's checkout from the L3 memory pack. The file is excluded from git.
pub fn memory_file(pack_markdown: &str, role: WorkerRole, task: Option<&Task>) -> String {
    let mut s = String::new();
    let target = match task {
        Some(t) => format!("{} on {}: {}", role.label(), t.key, one_line(&t.title)),
        None => role.label().to_string(),
    };
    let _ = writeln!(
        s,
        "<!-- Generated by {PRODUCT_NAME} for {target}. Do not edit or commit: this file is rewritten at the start of every run and is excluded from git. -->\n"
    );
    let _ = writeln!(s, "# {PRODUCT_NAME} worker context\n");
    let _ = writeln!(
        s,
        "This file was generated by {PRODUCT_NAME} from the company memory for the **{target}** run. \
It lists conventions, decisions and procedures learned from earlier work on this codebase.\n"
    );
    s.push_str("## How to use this\n\n");
    s.push_str(
        "- Treat these items as strong guidance from previous work. If one contradicts the code or your task, the task and the code win — mention the conflict in your summary.\n",
    );
    s.push_str("- Use the `search_memory` tool to look up anything not covered here.\n");
    s.push_str(
        "- When you learn something durable (a convention, a procedure that works, a non-obvious gotcha and its fix), record it with `propose_memory`. Never include secrets.\n",
    );
    s.push_str("- If the repository has its own contributor guide (README, CONTRIBUTING, docs/), it still applies.\n\n");
    s.push_str("## Memory\n\n");
    s.push_str(&or_none(
        pack_markdown,
        "_No memory items yet for this project._",
    ));
    s.push('\n');
    s
}
